def detect_rhizome_rot(day: DailyForecastPoint) -> str | None:
    temp_mean = (day.temp_min + day.temp_max) / 2.0
    if (25.0 <= temp_mean <= 28.0) and (day.humidity_max >= 80.0):
        return "Rhizome Rot risk: weather conditions match threshold"
    return None


