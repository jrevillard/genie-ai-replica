// WIRING tests for the backing-file lifecycle hooks (David, 2026-10-12).
//
// backing-file-service.test.js covers the service's own behaviour. These two
// suites cover the half that is easy to regress silently: that the service is
// ACTUALLY CALLED from the two teardown paths, and in the right ORDER.
//
// Each mock asserts through a call-order array, so a hook that is removed — or
// moved after the graph sweep that raw-REMOVEs the files docs — fails here.

jest.mock('../shared-lib/logger', () => ({
  logger: { info: jest.fn(), error: jest.fn(), warn: jest.fn(), debug: jest.fn() }
}));
jest.mock('../shared-lib/tracing', () => ({
  withSpan: jest.fn(async (name, fn) => fn({ setAttribute: jest.fn() }))
}));
jest.mock('../shared-lib/db-connection-service', () => {
  const mockDb = require('./mocks/arango-mock').createMockDb();
  return { getConnection: jest.fn(() => Promise.resolve(mockDb)), __mockDb: mockDb };
});
jest.mock('../shared-lib/metrics', () => ({
  getMeter: () => ({ createCounter: () => ({ add: jest.fn() }) })
}));
jest.mock('../services/audit-service', () => ({
  writeAudit: jest.fn().mockResolvedValue(null)
}));

// Shared order log across both mocked collaborators — the whole point is the
// relative order, which two separate spies cannot express.
const order = [];
jest.mock('../services/backing-file-service', () => ({
  // Retract's split rule (David, 2026-10-12): bundles hard-deleted, sources
  // only marked Retracted. See backing-file-service.test.js for the per-kind
  // behaviour — this suite only asserts the hook is wired.
  retractBackingFiles: jest.fn(async (repo_id) => {
    order.push('retractBackingFiles');
    return { repo_id, deleted_bundles: [], marked_sources: [], skipped: [], failed: [], total: 0 };
  }),
  markIngested: jest.fn(async (repo_id) => {
    order.push('markIngested');
    return { repo_id, marked: [], skipped: 0, failed: [] };
  }),
  hardDelete: jest.fn(async (repo_id) => {
    order.push('hardDelete');
    return { repo_id, deleted: [], skipped: [], failed: [], total: 0 };
  }),
  listBackingFiles: jest.fn(async () => []),
  otherLiveRepoUsingFile: jest.fn(async () => null)
}));
jest.mock('../services/graph-retract-service', () => ({
  retractRepoGraph: jest.fn(async () => {
    order.push('retractRepoGraph');
    return { repo_id: 'r', retracted: true, dropped: [] };
  }),
  dropRepoGraphsForRepo: jest.fn(async () => []),
  workingGraphName: jest.fn(() => 'OKF_r')
}));
jest.mock('../services/frontmatter-service', () => ({
  buildVectorizedHead: jest.fn(() => Promise.resolve({ dim: 1024, per_field: {}, computed_at: 'now' }))
}));

const mockDb = require('../shared-lib/db-connection-service').__mockDb;
const backingFileService = require('../services/backing-file-service');
const repoService = require('../services/repository-service');
const lifecycleService = require('../services/lifecycle-service');

const ACTOR = { sub: 'steward-1', name: 'Steward', source_ip: '127.0.0.1' };
const REPO = '11111111-2222-4333-8444-555555555555';

beforeEach(() => {
  jest.clearAllMocks();
  mockDb._reset();
  order.length = 0;
});

describe('delete cascade wires backingFileService.hardDelete', () => {
  test('remove() hard-deletes the backing files', async () => {
    await mockDb
      .collection('okf_repositories')
      .save({ _key: REPO, repo_id: REPO, name: 'R', lifecycle_state: 'draft' });
    await repoService.remove(REPO, ACTOR);
    expect(backingFileService.hardDelete).toHaveBeenCalledTimes(1);
    expect(backingFileService.hardDelete.mock.calls[0][0]).toBe(REPO);
  });

  test('ORDER: hardDelete runs BEFORE retractRepoGraph', async () => {
    // This ordering is load-bearing. retractRepoGraph's files sweep is a raw
    // Arango REMOVE; once it runs, the files docs are gone and hardDelete has
    // no file_id left to hand document-repository — the upload bytes would be
    // orphaned in the storage dir forever (no FK, no reclamation path).
    await mockDb
      .collection('okf_repositories')
      .save({ _key: REPO, repo_id: REPO, name: 'R', lifecycle_state: 'draft' });
    await repoService.remove(REPO, ACTOR);
    expect(order).toEqual(['hardDelete', 'retractRepoGraph']);
  });

  test('retract uses the SPLIT rule — bundles deleted, sources only marked', async () => {
    // David, 2026-10-12. A zip is regenerated by every publish (exportBundle
    // mints version N and writes <repo>-vN.zip), so deleting the bundle is
    // free. A steward's own upload is not ours to destroy on a reversible
    // transition, so sources are marked and NEVER deleted.
    await mockDb.collection('okf_repositories').save({
      _key: REPO,
      repo_id: REPO,
      name: 'R',
      lifecycle_state: 'publish',
      ingested_at: new Date().toISOString(),
      ingested_version: 3
    });
    await lifecycleService.transition(REPO, 'retract', ACTOR);
    expect(backingFileService.retractBackingFiles).toHaveBeenCalledTimes(1);
    // The TERMINAL delete cascade is the only thing that hard-deletes.
    expect(backingFileService.hardDelete).not.toHaveBeenCalled();
  });

  test('a backing-file failure never fails the DELETE (best-effort cascade branch)', async () => {
    await mockDb
      .collection('okf_repositories')
      .save({ _key: REPO, repo_id: REPO, name: 'R', lifecycle_state: 'draft' });
    backingFileService.hardDelete.mockRejectedValueOnce(new Error('doc-repo unreachable'));
    const res = await repoService.remove(REPO, ACTOR);
    // The registry entry still goes — that is what "delete" means.
    expect(res.status).toBe('deleted');
  });

  test('a backing-file failure never fails the RETRACT either', async () => {
    await mockDb.collection('okf_repositories').save({
      _key: REPO,
      repo_id: REPO,
      name: 'R',
      lifecycle_state: 'publish',
      ingested_at: new Date().toISOString(),
      ingested_version: 3
    });
    backingFileService.retractBackingFiles.mockRejectedValueOnce(new Error('doc-repo unreachable'));
    const res = await lifecycleService.transition(REPO, 'retract', ACTOR);
    expect(res.ok).toBe(true);
    expect(res.lifecycle_state).toBe('retracted');
  });
});
