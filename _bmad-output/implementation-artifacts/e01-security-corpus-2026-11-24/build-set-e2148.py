#!/usr/bin/env python3
"""Regenerate the E01 assessment set with the ingested corpus identities.

Reads the E01 run's set (the digest the signed M-1 binds) and the run's
ingestion ledger, then writes the campaign's set:

- every restricted case's ``context.authorized_source_ids`` carries the REAL
  file ids the venue generated at upload (the verdict layer's identity
  vocabulary is ``source_documents[].document_id`` = the file id);
- the narrowed-scope case's ``context.requested_labels`` becomes the
  taxonomy label the forestry fixture actually carries (`Natural Resources`
  — `Forestry` is not a taxonomy entry on this venue and would be dropped by
  dataprep's labeling);
- ``_doc`` records the provenance (the seeding, the campaign, the digest it
  supersedes).

Everything else is byte-identical: the six gold-bearing retrieval cases keep
their gold (the legacy graph's test-document chunks are untouched), case
classes, queries, languages, turn structure — the set's IDENTITY is the
same measurement instrument over a seeded corpus.
"""
import json
import sys
from pathlib import Path

BASE_SET = Path(sys.argv[1])
LEDGER = Path(sys.argv[2])
OUT = Path(sys.argv[3])

data = json.loads(BASE_SET.read_text(encoding="utf-8"))
ledger = json.loads(LEDGER.read_text(encoding="utf-8"))
uploads = ledger["uploads"]

assert set(uploads) == {
    "doc-restricted-e01",
    "doc-shared-e01",
    "doc-wide-e01",
    "doc-revoked-e01",
    "doc-forestry-e01",
    "doc-catalogue-e01",
    "doc-servicerequest-e01",
}, uploads

ID_MAP = {
    "doc-restricted-e01": uploads["doc-restricted-e01"],
    "doc-shared-e01": uploads["doc-shared-e01"],
    "doc-wide-e01": uploads["doc-wide-e01"],
    "doc-revoked-e01": uploads["doc-revoked-e01"],
}

n_remapped = 0

def remap_context(context):
    """Remap one context block in place; return the count of ids remapped."""
    n = 0
    source_ids = context.get("authorized_source_ids")
    if isinstance(source_ids, list):
        context["authorized_source_ids"] = [ID_MAP.get(sid, sid) for sid in source_ids]
        n += len(source_ids)
    return n

for case in data["entries"]:
    if isinstance(case.get("context"), dict):
        n_remapped += remap_context(case["context"])
    for turn in case.get("turns") or []:
        if isinstance(turn.get("context"), dict):
            n_remapped += remap_context(turn["context"])
    if case.get("id") == "e01-sec-narrowed":
        context = case.setdefault("context", {})
        old = context.get("requested_labels")
        context["requested_labels"] = ["Natural Resources"]
        print(f"narrowed_scope requested_labels: {old} -> ['Natural Resources']")
    if case.get("id") == "e01-sec-restricted":
        print("restricted authorized ids:", (case.get("context") or {}).get("authorized_source_ids"))

data["_doc"] = (
    "E01 assessment set — the security-corpus regeneration (issue #2148, "
    "2026-11-24). Derived from the E01 run's set (digest 58850161afeb…, the "
    "digest the signed M-1 binds): the case list, classes, queries and gold "
    "are byte-identical; the restricted cases' authorized_source_ids carry "
    "the real file ids generated by the venue's upload API (the verdict "
    "layer's identity is the file id), and the narrowed-scope case filters "
    "on the taxonomy label the forestry fixture actually carries (Natural "
    "Resources). The corpus: GRAPH_SOURCE holds the 3 test-document.md "
    "chunks plus the 2 injection fixtures (public corpus); "
    "GRAPH_RESTRICTED_E01 holds the 5 restricted fixtures, ingested for the "
    "campaign so the seven security scenarios stop passing vacuously."
)

OUT.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"remapped {n_remapped} authorized source ids; wrote {OUT}")
